import { access, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

// Paseo evaluates a bundled server module without its source directory. Capture
// the installed asset path during npm prepare so runtime reads have a stable root.
const prompt = new URL("../DEFAULT_REVIEW_PROMPT.md", import.meta.url);
await access(prompt);
const reviewMcp = new URL("../server/review-mcp-entry.ts", import.meta.url);
await access(reviewMcp);
await writeFile(new URL("../server/review-prompt-path.generated.ts", import.meta.url),
  `// Generated by scripts/prepare-review-prompt.mjs; do not edit.\nexport const REVIEW_PROMPT_PATH = ${JSON.stringify(fileURLToPath(prompt))};\nexport const REVIEW_MCP_PATH = ${JSON.stringify(fileURLToPath(reviewMcp))};\nexport const REVIEW_TSX_LOADER = ${JSON.stringify(import.meta.resolve("tsx/esm"))};\n`);
