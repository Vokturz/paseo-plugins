function iconFor(name, brand) {
  if (brand.path) return brand;
  const icon = Object.values(simpleIcons).find((candidate) => candidate && candidate.slug === brand.slug);
  if (!icon) throw new Error(`simple-icons has no "${brand.slug}" slug (needed for "${name}")`);
  return { hex: icon.hex, path: icon.path };
}

function pngDataUri({ hex, path }) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="${SIZE}" height="${SIZE}"><path fill="#${hex}" d="${path}"/></svg>`;
  const png = new Resvg(svg, { fitTo: { mode: "width", value: SIZE } }).render().asPng();
  return `data:image/png;base64,${png.toString("base64")}`;
}

const entries = Object.entries(brands).map(([name, brand]) => [name, pngDataUri(iconFor(name, brand))]);
const body = entries.map(([name, uri]) => `  ${name}: "${uri}",`).join("\n");
const file = `// Generated by scripts/generate-provider-icons.mjs — run \`npm run generate:icons\`.\n// Brand marks from simple-icons; the OpenAI (codex) path is embedded because simple-icons\n// dropped its "openai" slug in v16.0.0. Do not edit by hand.\nexport const providerPng: Record<string, string> = {\n${body}\n};\n`;

writeFileSync(OUTPUT, file);
console.log(`Wrote ${entries.length} icons to ${OUTPUT}`);
